function titleOverlap(a, n) { const A = a.replace(/ /g, ''), N = n.replace(/ /g, ''); if (A.includes(N) || N.includes(A)) return true; for (let i = 0; i < N.length - 1; i++) if (A.includes(N.slice(i, i + 2))) return true; return false; }
function dramaPick(W, ban = DRAMA_BAN) {
  for (let i = 0; i < 30; i++) {
    if (W.k && U.chance(0.12)) return U.pick(W.k);
    // b · l은 장소 · 일 낱말과 그 꾸미는 말 (없는 장르는 a · n을 같이 쓴다)
    const n = U.pick(W.n), m = U.pick(W.n.filter(x => x !== n)), a = U.pick(W.a), b = W.b ? U.pick(W.b) : a, l = W.l ? U.pick(W.l) : n, p = U.pick(W.p);
    if ((p.includes('{a}') && titleOverlap(a, n)) || (p.includes('{b}') && titleOverlap(b, l))) continue;
    // 틀에 이미 있는 말과 낱말이 같으면(원정대 원정대 · 퀴즈 퀴즈쇼) 다시 뽑는다
    // 낱말 한 토막이 틀에 있는 말과 같거나(시골 생활 생활) 틀의 말을 품어도(시간여행자의 시간) 다시 뽑는다
    const lit = p.replace(/\{.\}/g, ' '), lw = lit.split(' ').filter(Boolean), same = w => lit.includes(w) || w.split(' ').some(x => lw.includes(x)) || lw.some(x => x.length >= 2 && w.includes(x));
    if ((p.includes('{n}') && same(n)) || (p.includes('{l}') && same(l))) continue;
    // 받침에 맞춰 조사를 고친다 ({n}는 → 은/는, {n}가 → 이/가, {n}와 → 과/와, {n}를 → 을/를)
    const t = p.replace('{a}', a).replace('{b}', b).replace('{n}', n).replace('{m}', m).replace('{l}', l)
      .replace(new RegExp(`(${n}|${m}|${l})(는|은|가|이|와|과|를|을)(?= |$)`, 'g'), (all, w, j) => josa(w, { 는: '은는', 은: '은는', 가: '이가', 이: '이가', 와: '과와', 과: '과와', 를: '을를', 을: '을를' }[j]));
    if (!ban.includes(t)) return t;
  }
  return W.k ? U.pick(W.k) : U.pick(W.a) + ' ' + U.pick(W.n);
}
